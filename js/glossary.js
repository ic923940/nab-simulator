// 같은 화면에서 같은 용어는 한 번만 기록
let seen = new Set();
export function resetTermLog() { seen = new Set(); }
function onOpen(e) {
  const t = e.target.closest?.('.term');
  if (!t || seen.has(t.dataset.term)) return;
  seen.add(t.dataset.term);
  track('term_help', { term: t.dataset.term });
}
document.addEventListener('mouseover', onOpen);
document.addEventListener('focusin', onOpen);

// 말풍선 하나를 화면에 띄워서 용어 옆에 붙임
let box = null;
function show(t) {
  if (!box) { box = document.createElement('div'); box.id = 'tipbox'; document.body.append(box); }
  box.textContent = t.querySelector('.tip').textContent;
  box.style.display = 'block';
  const r = t.getBoundingClientRect(), w = box.offsetWidth, h = box.offsetHeight;
  let x = Math.min(Math.max(8, r.left), innerWidth - w - 8);
  let y = r.bottom + 6;
  if (y + h > innerHeight - 8) y = r.top - h - 6;
  box.style.left = x + 'px'; box.style.top = y + 'px';
}
function hide() { if (box) box.style.display = 'none'; }
document.addEventListener('mouseover', (e) => { const t = e.target.closest?.('.term'); if (t) show(t); });
document.addEventListener('mouseout', (e) => { if (e.target.closest?.('.term')) hide(); });
document.addEventListener('focusin', (e) => { const t = e.target.closest?.('.term'); t ? show(t) : hide(); });
document.addEventListener('focusout', hide);
addEventListener('scroll', hide, true);
