// 용어 표시: term('srs', 'SRS') → 점선 밑줄 + 설명 말풍선
export function term(key, label) {
  const f = TERMS[key];
  if (!f) return esc(label);
  return `<span class="term" tabindex="0" data-term="${key}">${esc(label)}<span class="tip" role="tooltip">${esc(f())}</span></span>`;
}

// 그때그때 다른 설명을 붙일 때 (예: 지명권별 보호 조건 원문)
export function tip(label, text) {
  return `<span class="term" tabindex="0" data-term="custom">${esc(label)}<span class="tip" role="tooltip">${esc(text)}</span></span>`;
}

